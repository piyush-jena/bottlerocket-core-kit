// Prairie dog config path
const DEFAULT_CONFIG_FILE: &str = "/etc/prairiedog.toml";
// Kdump related binary paths
const MAKEDUMPFILE_PATH: &str = "/sbin/makedumpfile";
const KEXEC_PATH: &str = "/sbin/kexec";

// Mount points created prairiedog
const BOOT_MOUNT_PATH: &str = "/boot";

// Filesystems used for the boot partition. GRUB images use ext4; UKI images use FAT, since
// systemd-boot has to be able to read the partition from the firmware.
const BOOT_FS_EXT4: &str = "ext4";
const BOOT_FS_VFAT: &str = "vfat";

// Mount options for the FAT boot partition on UKI images.
//
// FAT stores no ownership or permission bits, so they are set for the whole filesystem: only root
// may read it. `shortname=winnt` and `iocharset=iso8859-1` keep name handling predictable.
//
// FAT also stores no extended attributes, so SELinux labels can't live on the filesystem, and
// there is no fcontext rule for /boot to fall back on because it is a separate filesystem. The
// label therefore has to be applied at mount time.
const VFAT_MOUNT_DATA: &str =
    "umask=0077,shortname=winnt,iocharset=iso8859-1,context=system_u:object_r:os_t:s0";

// Set by prepare-boot.service from /usr/share/bottlerocket/image-format.env. Only consulted when
// the partition table doesn't tell us which boot layout the image uses.
const UKI_IMAGE_ENV: &str = "UKI_IMAGE";

// Files generated by prairiedog
const KDUMP_LOGS_PATH: &str = "/var/log/kdump";
const LOG_FILE: &str = "prairiedog.log";
const DMESG_DUMP_FILE: &str = "dmesg.log";
const KDUMP_FILE: &str = "vmcore.dump";

// Stores how much memory was allocated for the crash kernel
const KEXEC_CRASH_SIZE: &str = "/sys/kernel/kexec_crash_size";
// Enables/disables the kexec_load/kexec_file_load syscalls
const KEXEC_LOAD_DISABLED: &str = "/proc/sys/kernel/kexec_load_disabled";
// Crash kernel additional CMD line parameters
const KEXEC_CMD_LINE: &str = "maxcpus=1 systemd.unit='capture-kernel-dump.service' nr_cpus=1 \
                              swiotlb=noforce cma=0 reset_devices cgroup_disable=memory \
                              udev.children-max=2 panic=10 nvme_core.admin_timeout=20 swiotlb=1";

// Used to pass None to nix::mount::mount
const NONE: Option<&'static [u8]> = None;

/// Stores arguments
